export function guidedBeat(storyId: string, scene: StoryScene): GuidedBeat {
  return (storyId === "dependency-injection" ? injection : inversion)[scene.id] ?? {
    title: scene.title,
    body: scene.body,
  };
}

export function guidedActionLabel(storyId: string, scene: StoryScene, id: string) {
  return guidedBeat(storyId, scene).options?.[id] ??
    scene.actions?.find((action) => action.id === id)?.label ?? id;
}
