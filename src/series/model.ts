export function episodeById(id: string | null | undefined): Episode {
  return episodes.find((e) => e.id === id) ?? episodes[0];
}
export function nextEpisode(episode: Episode): Episode | undefined {
  return episodes.find((e) => e.number === episode.number + 1);
}
